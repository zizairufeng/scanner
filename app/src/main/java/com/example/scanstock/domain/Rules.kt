package com.example.scanstock.domain

/**
 * 重复码的处理口径（三态），替代原先的「去重开 / 关」布尔开关。
 *
 * 为什么要从布尔升级成三态：盘点的真实需求是「这个码有几个」，
 * 而布尔开关只能表达「要 / 不要这条重复记录」，答不了数量问题。
 * 三态把三种互斥口径摆在一起，用户按场景选，语义不会再被误解。
 *
 * 三者共同点：**时间窗防刷屏在三种模式下都生效**——持续对准一个码
 * 都不会一秒记十几条。模式只决定「重复的那个码算不算、怎么算」。
 */
enum class DedupeMode(val label: String, val hint: String) {

    /**
     * 严格去重（默认）：列表里已有的码不再计入。
     * 适合资产盘点、序列号采集——同一个东西本来就该只出现一次。
     */
    STRICT("严格去重", "列表里已有的码不再计入"),

    /**
     * 计数聚合：重复扫到同一个码时，该行数量 +1，仍只占一行。
     * 适合箱数清点、同款商品计数——扫 50 个同款得到一行「×50」而不是 50 行。
     */
    COUNT("计数聚合", "重复码累加数量，只占一行"),

    /**
     * 允许重复：同一个码离开画面满时间窗后可再次录入，每次占新的一行。
     * 适合需要逐次留痕的特殊口径。
     */
    ALLOW("允许重复", "离开画面满时间窗后可再次录入");

    companion object {
        val DEFAULT = STRICT
    }
}

/**
 * 条码准入规则（白名单）。全部留空 = 不限制。
 *
 * 用途：货架上一个画面里往往同时存在多个码（商品码、箱码、货架位码），
 * 加上规则后只有符合特征的才会计入，从源头挡掉误扫，省掉事后逐条删。
 *
 * 设计取舍：三条规则是**与**关系（全部满足才通过），并且任何一条留空就跳过该条。
 * 这样「只填前缀」是最常见的用法，不需要用户理解组合逻辑。
 *
 * @param enabled 总开关。false 时 [CodeFilter.accepts] 恒为 true，连解析都不做
 * @param prefix  必须以此前缀开头；空串表示不限
 * @param length  必须恰好是此长度；0 表示不限
 * @param regex   必须匹配此正则；空串表示不限。非法正则**不会崩溃**，
 *                 会被当作「该条不限制」并让 CodeFilter 上报一个错误提示
 */
data class CodeRule(
    val enabled: Boolean = false,
    val prefix: String = "",
    val length: Int = 0,
    val regex: String = ""
) {
    /** 三条规则全空时视为「无实质限制」，UI 据此提示用户还没填内容 */
    fun isBlank(): Boolean = prefix.isEmpty() && length <= 0 && regex.isEmpty()
}

/**
 * 校验位自校验的处理口径（v1.5）。
 *
 * ## 它和 [CodeRule] 的区别
 *
 * [CodeRule] 是**用户定的**白名单（「我只要 69 开头的」）；
 * 本项是**码制自带的**数学约束（「EAN-13 的校验位必须算得对」）。
 * 前者是业务规则，后者是物理事实，所以它不该被塞进规则页，而是挂在识别引擎页。
 *
 * ## 为什么默认开启
 *
 * 盘点场景里**误识比漏识致命**：漏识补扫一次就行，误识会把错误数据直接写进库存。
 * 而 EAN / UPC 系列自带校验位，一次加权和就能挡掉绝大多数「解错一位」的误识。
 * 代价是纯算术、零依赖，没有理由不开。
 *
 * ⚠️ 但它**不能挡住全部误识**：mod-10 对「某些相邻位互换」是无感的（这是算法本身的
 * 已知局限）。所以它是「大幅降低」，不是「杜绝」。
 */
enum class ChecksumPolicy(val label: String, val hint: String) {

    /**
     * 开启校验（默认）：校验位算不对的码直接丢弃。
     *
     * 只对 [ChecksumVerifier.supportsChecksum] 为 true 的码制生效；
     * Code-128 / QR 等没有可校验校验位的码制一律放行，不受影响。
     */
    ENFORCE("开启校验", "校验位算不对的码直接丢弃，挡掉解错一位的误识"),

    /**
     * 关闭：不做校验位检查，行为与 v1.4.4 及更早版本完全一致。
     *
     * 逃生舱。万一将来发现某个码制的校验实现有问题，用户能立刻自行退回旧行为，
     * 而不用等下一个版本——这比「相信实现永远正确」更可靠。
     */
    OFF("关闭", "不做校验位检查，与旧版本行为一致");

    companion object {
        val DEFAULT = ENFORCE

        /** 按存盘序号还原；越界回落到默认口径，保证旧配置可读、坏配置不崩 */
        fun fromOrdinal(ordinal: Int): ChecksumPolicy =
            entries.firstOrNull { it.ordinal == ordinal } ?: DEFAULT
    }
}
