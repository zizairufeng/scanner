package com.example.scanstock.domain

/**
 * 设置面板的分页结构（纯逻辑，零 Android 依赖，可 JVM 单测）。
 *
 * ## 为什么要有分页
 *
 * v1.4 把「识别引擎」整块加进设置面板后，面板高度涨到了约 2000dp，
 * 而真机可见区只有 600~900dp。试过两版修法：
 *
 * - v1.4.1：给内容 Column 加 `verticalScroll` + `heightIn(max = 屏高×0.88)`；
 * - v1.4.2：把行内固定 `height(56dp)` 改成 `heightIn(min = 56dp)`，避免副标题折行被裁。
 *
 * 两版都没解决问题。原因是 `ModalBottomSheet` 的**测量-摆放循环**：
 * 滚动容器把自身高度报成无限大，sheet 的分档（半展开 / 全展开）在「内容无穷高」
 * 这个前提下算出来的摆放位置不可靠，最终仍然按内容撑满、把超出部分裁掉。
 *
 * v1.4.3 换掉这个思路：**不再让面板高度依赖内容**。
 * 面板高度由 [SettingsPage] 的内容量反推出来并钉死，每一页都保证塞得下，
 * 于是根本不需要滚动，翻页靠底部的固定按钮条完成——
 * 那条按钮条在 `ModalBottomSheet` 之外，不受任何测量循环影响，永远够得到。
 *
 * ## 高度预算（v1.4.4 修订：预算本身算错过一次）
 *
 * v1.4.3 把预算定成 360dp，事后按 Material3 默认排版逐项复算才发现**每页都超**：
 *
 * | 页面 | 复算实际高度 | v1.4.3 预算 | 溢出 |
 * |---|---|---|---|
 * | 扫码 | 513dp | 360dp | +153 |
 * | 识别 | 498dp | 360dp | +138 |
 * | 结果 | 389dp | 360dp | +29 |
 * | 规则 | 324dp | 360dp | −36 |
 *
 * 而当时内容区是 `Box(weight(1f))`——**既不裁剪也不滚动**，
 * 于是溢出的 100 多 dp 直接盖在底部翻页条上，用户看到的就是「元素重叠」。
 * （v1.4.3 解决了「够不到」，却用「钉死但装不下」换来了「叠在一起」。）
 *
 * v1.4.4 双管齐下：
 *  1. **预算调到 520dp**，依据是「面板总高 ≤ sheet 在 927dp 屏上的最大高度 834dp」；
 *  2. **内容区改为固定高度内可滚动**——预算再算错也只是变成滚动，不会重叠。
 *     这一条是真正的保险：**不要相信任何一次性的高度估算**。
 *
 * 极限情况：无障碍字号放大时文字高度翻倍，仍可能超过预算，
 * 此时靠第 2 条兜住（滚动），不会退化成重叠。
 */
enum class SettingsPage(
    /** 分类标签上的短名 */
    val label: String,
    /** 页面标题下方的一句话说明 */
    val subtitle: String
) {
    /** 日常最常用：用什么样的画面去扫 */
    SCAN("扫码", "识别反馈、变焦与扫完之后怎么处理"),

    /** v1.4 主战场：小码 / 复杂码识别率 */
    ENGINE("识别", "小码与复杂码识别率：增强识别、精读、分析分辨率"),

    /**
     * v1.5 由「规则」扩为「准确」：把**两道「哪些码该被接受」的关卡**放在一起。
     *
     * 两项的机制完全不同（[ChecksumPolicy] 是码制自带的数学约束，
     * [CodeRule] 是用户定的白名单），但**用户要解决的问题是同一个**：
     * 「我不想让解错的 / 不该要的码进列表」。按问题而不是按实现分页，更好找。
     */
    ACCURACY("准确", "校验位检查 + 白名单过滤，挡住解错与不该要的码"),

    /** 去重口径、时间窗 */
    DATA("结果", "重复码怎么算、同码间隔多长");

    companion object {
        /**
         * 面板的固定开销（dp）：拖拽把手 + 标题 + 页面说明 + 分类标签条
         * + 上下内边距 + 底部翻页条。与 SettingsSheet 里逐项累加的值一致
         * （复算为 198，取整 210 留余量）。
         */
        const val PANEL_FIXED_OVERHEAD_DP: Int = 210

        /**
         * 单个分页的内容高度预算（dp）。
         *
         * 取值依据（不是拍脑袋）：
         * - 927dp 高的屏幕上，`ModalBottomSheet` 最大高度约 90% ≈ **834dp**；
         * - 扣掉 [PANEL_FIXED_OVERHEAD_DP] 210dp，内容最多能分到 **624dp**；
         * - 取 **545dp**，给自己留约 79dp 的容错余量。
         *
         * 为什么从 v1.4.4 的 520 又抬到 545：v1.5 给识别页加了「小码精读」开关，
         * 该页复算高度升到 **491dp**，520 虽然仍装得下但只剩 29dp 余量——
         * 估算一偏就要滚动。545dp 把这个余量提到 54dp。
         *
         * v1.7 再抬到 **610**：识别页新增「双引擎补扫」开关，复算高度约 **563dp**；
         * 610 给它留出 47dp 余量。同时 210 + 610 = 820 ≤ sheet 上限 834，
         * 仍在「面板总高不超过 sheet」这条硬约束之内（超出就会被 sheet 从底部裁掉，
         * 那时加多少滚动都没用）。
         *
         * 这也是「预算」与「兜底」分工的地方：预算只是让**默认不用滚**，
         * 真的超了由内容区的滚动兜住，不会像 v1.4.3 那样退化成重叠。
         */
        const val PAGE_HEIGHT_BUDGET_DP: Int = 610

        /**
         * `ModalBottomSheet` 在 927dp 屏幕上的最大可用高度（约屏幕的 90%）。
         *
         * 面板总高必须 ≤ 它，否则 sheet 自己会把底部裁掉——
         * 那时候加多少滚动都没用。
         */
        const val SHEET_MAX_HEIGHT_DP: Int = 834

        /** 面板总高 = 固定开销 + 内容预算。UI 与单测都从这里取，避免两边脱节。 */
        val PANEL_TOTAL_HEIGHT_DP: Int
            get() = PANEL_FIXED_OVERHEAD_DP + PAGE_HEIGHT_BUDGET_DP

        /** 第一页。打开设置面板时总是停在这里 */
        val DEFAULT: SettingsPage = SCAN

        /** 越界回落到默认页，保证旧状态 / 坏配置不崩 */
        fun fromOrdinal(ordinal: Int): SettingsPage =
            entries.firstOrNull { it.ordinal == ordinal } ?: DEFAULT

        /**
         * 循环翻到下一页。最后一页的下一页回到第一页——翻页按钮只有一个，
         * 不做「到末尾变灰」的禁用态，少一个状态就少一处出错的地方。
         */
        fun next(current: SettingsPage): SettingsPage {
            val n = entries.size
            return entries[(current.ordinal + 1) % n]
        }
    }
}
